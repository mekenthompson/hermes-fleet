#!/usr/bin/env python3
"""Widen the pinned Honcho plugin's machine-generated-turn filter (HF-657).

The plugin's ``_INTERNAL_GATEWAY_TURN_RE`` only knew a few wrapper forms, so
heartbeats, background-process notices, system continuations and
internal-notification turns were synced as the human's messages. This script
replaces the plugin's regex and ``_is_internal_gateway_turn`` with the version
below. It fails closed when the pinned plugin no longer has the expected block.

Upstream (plastic-labs/honcho 18fe5dd1) later added its own ``[Group chat:`` /
``[Discussion:`` harness alternative to the same regex. The replacement block keeps
that alternative, so the result is a strict superset of both upstream's filter and
the HF-657 wrapper set; the Bot Mode / hosted-room harness turn is dropped whole.

No structural signal exists: the gateway injects these as plain role=user text
and ``MemoryManager.sync_all`` forwards only ``turn_author`` (None for them), so
detection is textual and start/end anchored. A human message that merely quotes
a wrapper mid-text, or replies to one, is still synced.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

NEW_BLOCK = r'''_INTERNAL_GATEWAY_TURN_RE = re.compile(
    r"^\s*(?:"
    r"\[ASYNC (?:DELEGATION )?(?:BATCH )?COMPLETE[^\]]*\]|"
    r"\[CONTEXT COMPACTION[^\]]*\]|"
    r"\[CONTEXT SUMMARY\]:?|"
    r"\[PRIOR CONTEXT[^\]]*\]|"
    r"\[Your active task list was preserved across context compression\]|"
    r"\[Heartbeat\s*[\u2014\u2013-]\s*recurring instruction[^\]]*\]|"
    r"\[IMPORTANT: Background process \S+ (?:matched watch pattern|completed|exited|finished|failed|was killed)[^\n]*|"
    r"\[System: Continue now\.[^\]]*\]|"
    r"\[(?:Group chat|Discussion):|"
    r"A background fan-out of \d+ subagent\(s\) you dispatched earlier has finished\.|"
    r"A background subagent you dispatched earlier has finished\."
    r")",
    re.IGNORECASE,
)
# The gateway appends this footer to model-facing notifications (the body may start with anything).
_INTERNAL_NOTIFICATION_FOOTER_RE = re.compile(
    r"\[INTERNAL NOTIFICATION \u2014 generated by the Hermes gateway, not written by a human user\.[^\]]*\]\s*\Z",
    re.IGNORECASE,
)
# Prefixes the gateway/memory layer may put in front of a turn; they must not defeat the anchor.
_REPLY_POINTER_RE = re.compile(
    r'\A\s*(?:\[Triggering message id: [^\n]*\]\n\n)?\[Replying to(?: your previous message)?: ".*?"\]\n\n',
    re.DOTALL,
)


def _is_internal_gateway_turn(text: str) -> bool:
    """Return True for machine-generated gateway/delegation notifications (HF-657)."""
    text = text or ""
    try:
        text = sanitize_context(text)  # strips leading <memory-context> blocks
    except Exception:
        pass
    text = _REPLY_POINTER_RE.sub("", text, count=1)
    return bool(_INTERNAL_GATEWAY_TURN_RE.match(text) or _INTERNAL_NOTIFICATION_FOOTER_RE.search(text))
'''

_OLD_BLOCK_RE = re.compile(
    r"_INTERNAL_GATEWAY_TURN_RE = re\.compile\(\n.*?\n\)\n\n\ndef _is_internal_gateway_turn\(text: str\) -> bool:\n"
    r"    \"\"\"[^\n]*\"\"\"\n    return bool\(_INTERNAL_GATEWAY_TURN_RE\.match\(text or \"\"\)\)\n",
    re.DOTALL,
)


def patch_source(source: str) -> str:
    if "_INTERNAL_NOTIFICATION_FOOTER_RE" in source:
        return source  # already patched
    new, count = _OLD_BLOCK_RE.subn(lambda _m: NEW_BLOCK, source, count=1)
    if count != 1:
        raise SystemExit("honcho plugin: expected _INTERNAL_GATEWAY_TURN_RE block not found; review the pin")
    if "from agent.memory_manager import sanitize_context" not in new:
        raise SystemExit("honcho plugin: sanitize_context import not found; review the pin")
    return new


def main(argv: list[str]) -> int:
    path = Path(argv[1] if len(argv) > 1 else "/opt/hermes/plugins/memory/honcho/__init__.py")
    path.write_text(patch_source(path.read_text(encoding="utf-8")), encoding="utf-8")
    print(f"patched {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
