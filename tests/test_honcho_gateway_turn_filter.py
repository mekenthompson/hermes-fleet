class FilterBehaviour(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.patched_source = patcher.patch_source(FIXTURE.read_text(encoding="utf-8"))
        cls.is_internal = staticmethod(_load(cls.patched_source))

    def test_each_wrapper_form_is_skipped(self):
        for name, text in WRAPPERS.items():
            with self.subTest(name):
                self.assertTrue(self.is_internal(text))

    def test_wrapper_behind_memory_context_or_reply_pointer_is_skipped(self):
        mc = "<memory-context>\nrecall\n</memory-context>\n\n"
        for name in ("heartbeat", "process_completed", "system_continue"):
            with self.subTest(name):
                self.assertTrue(self.is_internal(mc + WRAPPERS[name]))
                self.assertTrue(self.is_internal(f'[Replying to: "hi"]\n\n{WRAPPERS[name]}'))

    def test_human_text_still_syncs(self):
        for name, text in HUMAN.items():
            with self.subTest(name):
                self.assertFalse(self.is_internal(text))

    def test_empty_inputs(self):
        self.assertFalse(self.is_internal(""))
        self.assertFalse(self.is_internal(None))

    def test_upstream_harness_filter_is_kept(self):
        """Upstream 18fe5dd1 already drops group-chat/hosted-room harness turns; the patch must not lose that."""
        old = _load(FIXTURE.read_text(encoding="utf-8"))
        for name in ("group_chat_harness", "hosted_discussion_harness"):
            with self.subTest(name):
                self.assertTrue(old(WRAPPERS[name]), "fixture no longer carries upstream's harness filter")
                self.assertTrue(self.is_internal(WRAPPERS[name]))

    def test_unpatched_plugin_missed_the_new_forms(self):
        """Guards the fixture: the pre-patch filter really had the HF-657 gap."""
        old = _load(FIXTURE.read_text(encoding="utf-8"))
        self.assertFalse(old(WRAPPERS["heartbeat"]))
        self.assertFalse(old(WRAPPERS["process_completed"]))
        self.assertFalse(old(WRAPPERS["system_continue"]))
        self.assertFalse(old(WRAPPERS["internal_footer_tail"]))
        self.assertTrue(old(WRAPPERS["async_batch_emdash"]))


class Patcher(unittest.TestCase):
    def test_idempotent(self):
        once = patcher.patch_source(FIXTURE.read_text(encoding="utf-8"))
        self.assertEqual(patcher.patch_source(once), once)

    def test_fails_closed_when_block_missing(self):
        with self.assertRaises(SystemExit):
            patcher.patch_source("from agent.memory_manager import sanitize_context\nx = 1\n")

    def test_fails_closed_when_sanitize_import_missing(self):
        source = FIXTURE.read_text(encoding="utf-8").replace("from agent.memory_manager import sanitize_context\n", "")
        with self.assertRaises(SystemExit):
            patcher.patch_source(source)

    def test_fails_closed_when_upstream_reshapes_the_helper(self):
        source = FIXTURE.read_text(encoding="utf-8").replace("def _is_internal_gateway_turn(text: str) -> bool:", "def _is_internal_gateway_turn(text: str, *, strict: bool = False) -> bool:")
        with self.assertRaises(SystemExit):
            patcher.patch_source(source)

    def test_dockerfile_runs_patcher_after_plugin_install(self):
        text = (ROOT / "Dockerfile").read_text(encoding="utf-8")
        install = text.index("hermes-plugin-honcho/.")
        run = text.index("patch-honcho-gateway-turn-filter.py /opt/hermes/plugins/memory/honcho/__init__.py")
        self.assertLess(install, run)


if __name__ == "__main__":
    unittest.main()
